import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
const source = readFileSync(new URL("../updater/desktop-update.mjs", import.meta.url), "utf8");
const sha256 = createHash("sha256").update(source).digest("hex");
writeFileSync(new URL("../updater/helper-source.ts", import.meta.url), `// Generated by scripts/gen-helper-source.mjs from updater/desktop-update.mjs. Do not edit.\nexport const HELPER_SHA256 = ${JSON.stringify(sha256)};\nexport const HELPER_SOURCE = ${JSON.stringify(source)};\n`);
