// Captures the pre-rendered loops. Run from helper-desk/:
//   node scripts/build-strips.mjs
//   HD_STRIPS_ONLY=navn node scripts/build-strips.mjs     (re-capture one or more characters, keep the rest as they are)
// It bundles capture-entry.ts, serves it on 127.0.0.1 only, opens it in headless Chrome through agent-browser,
// and writes mascots3d/strips.generated.ts from what the page posts back. Nothing leaves this machine.
import { createServer } from "node:http";
import { execFileSync, spawn, spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const out = join(root, "mascots3d", "strips.generated.ts");
const work = process.env.HD_STRIPS_WORK ?? "/tmp/hd-3d/capture";
const only = (process.env.HD_STRIPS_ONLY ?? "").split(",").filter(Boolean);
mkdirSync(work, { recursive: true });

function findEsbuild() {
  if (process.env.ESBUILD) return process.env.ESBUILD;
  const plugins = join(homedir(), ".bb", "plugins");
  const dir = existsSync(plugins) ? readdirSync(plugins).find((d) => d.startsWith("toolchain-")) : null;
  if (dir) return join(plugins, dir, "node_modules", ".bin", "esbuild");
  return "esbuild";
}

execFileSync(findEsbuild(), [join(here, "capture-entry.ts"), "--bundle", "--format=iife", `--outfile=${join(work, "capture.js")}`, "--log-level=warning"], { stdio: "inherit" });
writeFileSync(join(work, "capture.html"), `<!doctype html><meta charset="utf-8"><body><script src="/capture.js"></script>`);

const strips = {};
let finished;
const done = new Promise((res, rej) => (finished = { res, rej }));

const server = createServer((req, res) => {
  const url = new URL(req.url, "http://127.0.0.1");
  if (req.method === "GET") {
    const file = url.pathname === "/" ? "capture.html" : url.pathname.slice(1);
    if (!/^[\w.]+$/.test(file) || !existsSync(join(work, file))) return res.writeHead(404).end();
    res.writeHead(200, { "content-type": file.endsWith(".js") ? "text/javascript" : "text/html" }).end(readFileSync(join(work, file)));
    return;
  }
  const chunks = [];
  req.on("data", (c) => chunks.push(c));
  req.on("end", () => {
    const body = Buffer.concat(chunks).toString();
    if (url.pathname === "/strip") strips[url.searchParams.get("key")] = body;
    if (url.pathname === "/done") finished.res(Number(url.searchParams.get("count")));
    if (url.pathname === "/fail") finished.rej(new Error(body));
    res.writeHead(204).end();
  });
});

await new Promise((r) => server.listen(0, "127.0.0.1", r));
const port = server.address().port;
const opener = spawn("agent-browser", ["open", `http://127.0.0.1:${port}/?only=${only.join(",")}`], { stdio: "ignore" });
opener.on("error", (e) => finished.rej(e));
const count = await Promise.race([done, new Promise((_, rej) => setTimeout(() => rej(new Error("capture timed out")), 15 * 60_000))]);
server.close();
spawnSync("agent-browser", ["close"], { stdio: "ignore" });

if (only.length && existsSync(out)) {
  for (const [, key, uri] of readFileSync(out, "utf8").matchAll(/^  ("[^"]+"): ("data:[^"]*"),$/gm)) {
    const k = JSON.parse(key);
    if (!only.includes(k.split(":")[0])) strips[k] = JSON.parse(uri);
  }
}
const keys = Object.keys(strips).sort();
let bytes = 0;
const lines = keys.map((k) => {
  bytes += strips[k].length;
  return `  ${JSON.stringify(k)}: ${JSON.stringify(strips[k])},`;
});
writeFileSync(out, `// Generated by scripts/build-strips.mjs. Do not edit.\nexport const STRIPS: Record<string, string> = {\n${lines.join("\n")}\n};\n`);
console.log(`${count} strips, ${(bytes / 1024).toFixed(0)} KiB of data URIs -> ${out}`);
process.exit(0);
